#!/usr/bin/env python3
"""Generate data/nowItems.ts from content/now markdown files (mini-posts)."""

from __future__ import annotations

import json
import os
import sys
from datetime import datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from generate_blog_posts import PostParseError, normalize_content_block, parse_frontmatter  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
NOW_DIR = ROOT / "content" / "now"
OUTPUT_FILE = ROOT / "data" / "nowItems.ts"
KINDS = {"paper", "code", "project"}


def parse_item(source: Path) -> dict:
    import re

    raw = source.read_text(encoding="utf-8")
    frontmatter, body = parse_frontmatter(raw, source)

    missing = [field for field in ["title", "date", "kind", "summary"] if not frontmatter.get(field)]
    if missing:
        raise PostParseError(f"{source}: missing required fields: {', '.join(missing)}")

    try:
        datetime.strptime(frontmatter["date"], "%Y-%m-%d")
    except ValueError as exc:
        raise PostParseError(f"{source}: invalid date '{frontmatter['date']}'") from exc

    kind = frontmatter["kind"].strip().lower()
    if kind not in KINDS:
        raise PostParseError(f"{source}: kind must be one of {sorted(KINDS)}")

    paragraphs = [normalize_content_block(part) for part in re.split(r"\n\s*\n", body) if part.strip()]
    tags = [tag.strip() for tag in frontmatter.get("tags", "").split(",") if tag.strip()]

    item = {
        "id": source.stem,
        "title": frontmatter["title"],
        "date": frontmatter["date"],
        "kind": kind,
        "summary": frontmatter["summary"],
        "content": paragraphs,
        "tags": tags,
    }
    for key, out in [("link", "link"), ("github", "github"), ("link_label", "linkLabel")]:
        if frontmatter.get(key):
            item[out] = frontmatter[key]
    item["draft"] = frontmatter.get("draft", "").strip().lower() in {"true", "yes", "1"}
    return item


def generate() -> None:
    NOW_DIR.mkdir(parents=True, exist_ok=True)
    items = [parse_item(path) for path in sorted(NOW_DIR.glob("*.md"))]

    include_drafts = os.environ.get("INCLUDE_DRAFTS", "").strip().lower() in {"1", "true", "yes"}
    skipped = [item for item in items if item["draft"] and not include_drafts]
    items = [item for item in items if include_drafts or not item["draft"]]
    for item in items:
        item.pop("draft")
    items.sort(key=lambda item: (item["date"], item["title"].lower()), reverse=True)

    content = (
        "import { NowItem } from '../types';\n\n"
        "// This file is auto-generated by scripts/generate_now.py\n"
        f"export const NOW_ITEMS: NowItem[] = {json.dumps(items, indent=2, ensure_ascii=False)};\n"
    )
    OUTPUT_FILE.write_text(content, encoding="utf-8")
    print(f"Generated {OUTPUT_FILE} from {len(items)} item(s).")
    for item in skipped:
        print(f"Skipped draft: {item['id']} (set INCLUDE_DRAFTS=1 to include)")


if __name__ == "__main__":
    try:
        generate()
    except PostParseError as exc:
        print(f"Error: {exc}", file=sys.stderr)
        raise SystemExit(1)
